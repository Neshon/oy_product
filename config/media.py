"""Раздача загруженных файлов — изображений плат.

Штатный ``django.conf.urls.static.static`` подключает маршрут только при
``DEBUG``, и это верно для сборки с nginx впереди: прокси перехватывает
``/media/`` раньше Django, и возить байты через Python незачем.

Обратного прокси в текущей сборке нет — приложение опубликовано напрямую,
см. шапку ``docker-compose.yml``. Без этого маршрута в контейнере
получалось самое неприятное: файлы на месте, в базе правильный путь, а
``/media/...`` отвечает 404, и выглядит это как «изображения пропали».
Локально всё работало, потому что там ``DEBUG`` включён, — то есть ошибка
вылезала только на сервере.

Когда nginx появится, менять здесь ничего не нужно: он перехватит
``/media/`` раньше, и маршрут просто перестанет использоваться.
"""

from django.conf import settings
from django.views.static import serve


def media_file(request, path):
    """Отдаёт файл из ``MEDIA_ROOT``.

    Вход обязателен: маршрут не помечен ``login_not_required``, поэтому его,
    как и обычные страницы, закрывает ``LoginRequiredMiddleware``. Это
    строже, чем было бы за nginx: тот отдаёт файлы кому угодно, и разница
    между средами здесь в пользу этого варианта.

    ``serve`` проверяет, что запрошенный путь не уводит выше каталога, сам
    определяет тип содержимого и отвечает на условные запросы — браузер
    получает 304 вместо файла, пока снимок не менялся.

    Способ не бесплатный: файл едет через gunicorn и занимает работника на
    время передачи. Для снимков плат внутренней системы это незаметно; если
    однажды станет заметно, ответ — nginx, а не оптимизация этого
    представления.
    """
    return serve(request, path, document_root=settings.MEDIA_ROOT)
