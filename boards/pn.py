"""Единое правило записи партномера.

Точки в номере — оформление, а не часть имени: одну и ту же плату пишут и
``HSFP-SCM.01``, и ``HSFP-SCM01``, причём обе записи встречаются в одном
BOM. Разделители ``-`` и ``_`` при этом остаются: они разделяют части
номера, а не украшают его.

Правило нужно в двух разных видах, и путать их нельзя:

* :func:`canonical` — как номер **хранится и показывается**. Точки убраны,
  регистр и разделители на месте: это по-прежнему тот номер, который
  человек прочтёт в реестре и наберёт в поиске;
* :func:`match_key` — как номера **сравниваются** между собой. Сверх
  canonical снимается регистр и все пробелы. Ключ наружу не показывается,
  и терять в нём нечего — зато ``HSBP-5S.01`` из Confluence и
  ``hsbp-5s01`` из BOM сойдутся.

Почему в отдельном модуле, а не в :mod:`boards.revisions`: этим правилом
пользуются и импорт Confluence, и формы, и поиск, и standalone-скрипт
``tools/confluence_parse.py``. Зависимостей от Django здесь намеренно нет,
поэтому модуль импортируется и без настроенного окружения.

Раньше оба правила были написаны заново в шести местах и успели
разойтись: где-то снимались пробелы, где-то нет, где-то поднимался
регистр. Сойдутся два номера или нет, зависело от того, через какой файл
они пришли.
"""

import re

_SPACES = re.compile(r"\s+")


def canonical(part_number):
    """Номер в единой записи — без точек.

    ``HSFP-SCM.01`` и ``HSFP-SCM01`` — одна плата. Регистр и разделители
    ``-``/``_`` сохраняются: это значение уходит в базу и на экран.
    """
    return (part_number or "").replace(".", "").strip()


def match_key(part_number):
    """Ключ для сравнения номеров: без точек, без пробелов, в верхнем регистре.

    Годится только для сопоставления — показывать его нельзя, он не
    совпадает с тем, как номер записан в документах.
    """
    return _SPACES.sub("", canonical(part_number)).upper()
