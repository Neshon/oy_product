"""Ревизии, зашитые в номер платы.

Номер вида ``HSBP-5S01-02C`` состоит из трёх частей:

* ``HSBP-5S01`` — сама плата, она же связывает ревизии между собой;
* ``02`` — ревизия платы: первая цифра до точки, остальные после (``0.2``,
  ``102`` → ``1.02``);
* ``C`` — ревизия BOM.

Поэтому ``HSBP-5S01-02C`` и ``HSBP-5S01-02D`` — не две разные платы, а два
ревизии одной: разные ревизии BOM при одной ревизии платы.

Перед ревизиями может стоять исполнение: ``HSBP-5S01-R-02D`` — та же плата
в российской сборке. Исполнение в базовый номер не входит, иначе реестр
показывал бы две платы там, где она одна, и половина ревизий уходила бы к
каждой. Хранится оно у ревизии — см. ``BoardRevision.variant``.

Базовый номер приводится к записи без точек — иначе в реестре получаются
две платы, у каждой своя половина ревизий. Само правило записи номера
лежит в :mod:`boards.pn`: им пользуется не только разбор ревизий.

Если номер под правило не подходит (плата заведена вручную, имя взято из
файла), он целиком считается базовым, а ревизии остаются пустыми — терять
номер хуже, чем не разобрать ревизию.
"""

import re

from .pn import canonical

# Номер ревизии: имя платы, затем ревизия платы цифрами, затем ревизия BOM.
# Между ними может стоять признак локализации «R» — вплотную к цифрам:
#
#   HSBP-5S01-02C         база HSBP-5S01,   плата 0.2,  BOM C
#   RSRB-CRS202H-R-12RA   база RSRB-CRS202H, плата 1.2, BOM A,  локализация
#   RSMB-MS93-R-102A1     база RSMB-MS93,   плата 1.02, BOM A1, локализация
#   RBR-CRS2033R-10RF     база RBR-CRS2033, плата 1.0,  BOM F,  локализация
#   RBR-CRS101ER-10R      база RBR-CRS101E, плата 1.0,  BOM нет, локализация
#
# Ревизия BOM — буква и, если есть, одна цифра при ней (A, C, A1). Её
# может не быть вовсе: «-10R» — это ревизия платы 1.0 с локализацией, а не
# ревизия BOM «R». Так пишут в паре с локализацией в самом имени
# (RBR-CRS101ER-10R), и «R» здесь повторяет её, а не нумерует BOM.
#
# Имя платы забирается жадно, до последнего дефиса, а хвост после него
# должен разобраться целиком. Иначе «HSBP-5S01» — имя платы без всяких
# ревизий — читалось бы как плата «HSBP» ревизии 5 с BOM «S01»: формально
# такое разбиение шаблону подходит.
PN_RE = re.compile(
    r"^(?P<base>.+)-(?P<digits>\d{1,4})(?P<local>R)?(?P<bom>[A-Za-z]\d?)?$")

# Известные исполнения. Список закрытый: снимать с номера любой короткий
# хвост нельзя — так у платы, названной «...-A», отрезало бы часть имени
VARIANTS = ("R",)
VARIANT_RE = re.compile(r"^(?P<base>.+)-(?P<variant>" + "|".join(VARIANTS)
                        + r")$", re.IGNORECASE)

# Локализация пишется и слитно с именем: RBR-CRS2033R, RBR-CRS101ER.
# Отрезаем её только у кода — последней части имени, где есть цифры:
# «CRS101ER» это код с локализацией, а «PWR» или «SENSOR» — слово, и
# отрезать у него хвост значит испортить имя.
GLUED_RE = re.compile(r"^(?P<base>.*[-_][A-Za-z0-9.]*\d[A-Za-z0-9.]*?)"
                      r"(?P<variant>R)$")


def split_variant(base_pn):
    """Отделяет локализацию от имени платы: (имя, локализация).

    Локализация встречается в двух видах — отдельной частью номера
    (``HSBP-5S01-R``) и слитно с именем (``RBR-CRS2033R``). И то и другое
    означает одно: та же плата, собранная в другом месте.
    """
    text = (base_pn or "").strip()
    match = VARIANT_RE.match(text) or GLUED_RE.match(text)
    if not match:
        return text, ""
    return match.group("base"), match.group("variant").upper()


def parse_pn(oy_pn):
    """Возвращает (базовый номер, ревизия платы, ревизия BOM).

    Базовый номер — без локализации и без точек: ``HSBP-5S01-02C``,
    ``HSBP-5S01-R-02D`` и ``HSBP-5S.01-01A`` дают один и тот же
    ``HSBP-5S01``. Локализацию берут через :func:`variant_of` — она
    относится к ревизии, а не к плате.
    """
    text = (oy_pn or "").strip()
    match = PN_RE.match(text)
    if not match:
        return canonical(split_variant(text)[0]), "", ""

    digits = match.group("digits")
    # первая цифра — до точки, остальные после: 02 → 0.2, 102 → 1.02
    board_rev = f"{digits[0]}.{digits[1:]}" if len(digits) > 1 else digits
    base_pn, _ = split_variant(match.group("base"))
    bom_rev = (match.group("bom") or "").upper()
    return canonical(base_pn), board_rev, bom_rev


def variant_of(oy_pn):
    """Локализация из номера ревизии: «R» или пусто.

    Ищется в обоих местах: и в имени платы, и вплотную к ревизии платы
    (``-12RA``) — в номере она встречается то там, то там.
    """
    text = (oy_pn or "").strip()
    match = PN_RE.match(text)
    if match:
        if match.group("local"):
            return "R"
        return split_variant(match.group("base"))[1]
    return split_variant(text)[1]


def revision_counter(board_rev):
    """Счётчик из номера: «0.2» → 2, «1.1» → 11, «1.02» → 102.

    Точка в ревизии платы — только разделитель при показе, поэтому убрать
    её и значит вернуть исходный счётчик из номера ревизии.
    Что не разобралось — ``-1``, такие ревизии уходят в конец.
    """
    digits = (board_rev or "").replace(".", "").strip()
    return int(digits) if digits.isdigit() else -1


def sort_key(revision):
    """Порядок ревизий: сначала счётчик ревизии платы, потом ревизия BOM.

    Считать нужно именно по счётчику из номера, а не как дробное число:
    ревизии идут 02 → 10 → 11 → 12 → 101 → 102, то есть ``1.02`` новее
    ``1.1``. Сравнение «0.2 < 1.02 < 1.1» дало бы обратный порядок и
    показало бы устаревший состав как текущий.
    Что не разобралось, уходит в конец, но не теряется.
    """
    return revision_counter(revision.board_rev), revision.bom_rev or "", revision.number
