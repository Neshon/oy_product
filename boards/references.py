"""Обозначения позиций на плате: «C1,C4,C7».

В приходящих BOM разделитель какой угодно: где-то запятые, где-то только
пробелы, где-то точки с запятой или всё вперемешку. Внутри мы храним
строку такой, какой она пришла — это снимок файла, — а приводим к общему
виду там, где её читают: при выгрузке и при разборе на список.
"""

import re

# запятая, точка с запятой и любые пробелы — всё это разделители
SEPARATORS = re.compile(r"[,;\s]+")

# запятая с пробелом: по запятой обозначения разбирает машина, а по
# пробелу переносит длинный список Excel и браузер
JOINER = ", "


def split_references(text):
    """Список обозначений, каким бы ни был разделитель в исходной строке."""
    if not text:
        return []
    return [part for part in SEPARATORS.split(str(text).strip()) if part]


def normalize_references(text):
    """Та же строка, но разделённая запятыми.

    Сами обозначения не трогаются: дефис в диапазоне «C1-C4» остаётся на
    месте, меняются только разделители между ними.
    """
    if not text:
        return text
    return JOINER.join(split_references(text))
