"""Служебные значения-заглушки, по которым нельзя сопоставлять записи.

В данных вместо пустой ячейки часто стоит «---», «?» или «-». Если по ним
искать совпадения, один компонент «находится» во всех платах, где заполнено
так же, — это ложные связи, а не аналоги.
"""

# Прочерк вместо значения: только тире и вопросительные знаки, без слов.
DASHES = {"", "-", "--", "---", "----", "—", "–", "?", "??", "???"}

# Всё, по чему нельзя сопоставлять записи. Сверх прочерков сюда входят
# слова — но именно поэтому список годится не везде: «нет» бессмысленно в
# артикуле и вполне осмысленно в ответе «в реестре МПТ — нет».
PLACEHOLDERS = DASHES | {
    "n/a", "na", "n.a.", "none", "null", "нет", "не указано", "tbd",
}


def is_placeholder(value):
    """Значение бессмысленно для сопоставления."""
    return normalize(value) in PLACEHOLDERS


def is_dash(value):
    """Прочерк вместо значения — и только он.

    Для случаев, где слова вроде «нет» несут смысл и выбрасывать их нельзя:
    показ сведений о ревизии, ответы в чек-листах. Отличается от
    :func:`is_placeholder` ровно этим.
    """
    return normalize(value) in DASHES


def normalize(value):
    return (value or "").strip().lower()


def usable(value):
    """Значение, по которому можно искать, либо пустая строка."""
    text = (value or "").strip()
    return "" if is_placeholder(text) else text
