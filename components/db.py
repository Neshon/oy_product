"""Что делать, когда база не ответила.

Таблицы компонентов ведём не мы: их могут переименовать, забрать права,
уронить схему — и приложение должно это пережить. Поэтому запросы к ним
обёрнуты, а страница открывается с тем, что удалось прочитать.

Раньше эта обёртка была написана заново в сорока восьми местах, и почти
везде — молча:

    try:
        ...
    except DatabaseError:
        return []

Каждое такое решение по отдельности разумное. В сумме получалась система,
которая при отвалившейся схеме показывает пустые фильтры, ноль аналогов и
неполный поиск, не сообщая об этом ни пользователю, ни в журнал. Отличить
«дублей нет» от «проверка не отработала» было нельзя.

Здесь то же поведение, но в одном месте и **с записью в журнал**. Что
именно деградировало, видно в логах; поведение для пользователя не
изменилось.

Два вида, по числу реальных случаев в коде:

* :func:`fallback` — «весь ответ заменяется запасным»: одна выборка, и без
  неё функции сказать нечего;
* :func:`unavailable` — «эта таблица выпала, идём к следующей»: обход по
  всем 27 таблицам, где одна недоступная не повод бросать остальные.

Чего здесь нет намеренно: случаев, когда об ошибке нужно сказать человеку.
Отказ базы при сохранении компонента или при импорте BOM — это не «нечего
показать», а «ваша работа не сохранена», и такие места по-прежнему ловят
``DatabaseError`` сами и пишут в ``messages``.
"""

import logging
from contextlib import contextmanager
from functools import wraps

from django.db import DatabaseError

logger = logging.getLogger(__name__)


def fallback(value, what=""):
    """Вернуть запасное значение, если база не ответила.

    ``value`` — что отдать вместо ответа. Если оно вызываемое, оно
    вызывается: так задаются изменяемые значения, чтобы вызывающие не
    делили один список на всех.

        @fallback(list, "значения фильтра")
        def _values(...):
            ...

        @fallback(lambda: ([], ""), "применение компонента")
        def find_usages(...):
            ...

    ``what`` — чем это было, человеческими словами. Уходит в журнал:
    «недоступна база: значения фильтра» читается, а имя функции — не
    всегда.
    """
    def decorator(func):
        @wraps(func)
        def wrapper(*args, **kwargs):
            try:
                return func(*args, **kwargs)
            except DatabaseError as exc:
                logger.warning("база не ответила (%s): %s",
                               what or func.__qualname__, exc)
                return value() if callable(value) else value
        return wrapper
    return decorator


@contextmanager
def unavailable(table, failed=None):
    """Пропустить недоступную таблицу и продолжить обход.

    Ставится внутрь цикла по категориям — так, чтобы в него попало всё
    тело шага:

        for category in CATEGORIES.values():
            with unavailable(category.table, failed):
                ...            # упало здесь — шаг просто закончится

    Исключение гасится, цикл идёт дальше. Имя таблицы попадает в
    ``failed``, если список передали: страницы показывают его человеку
    («не читаются таблицы: …»), и это важнее записи в журнале — молча
    отдать неполный отчёт по дублям хуже, чем не отдать никакого.
    """
    try:
        yield
    except DatabaseError as exc:
        logger.warning("таблица %s недоступна: %s", table, exc)
        if failed is not None:
            failed.append(table)
